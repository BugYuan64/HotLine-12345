"""敏感/紧急事件实时感知（需求 9(9) / API 10.7）

仅当诉求文本明确命中六大类情形之一才判定为敏感事件：
人身安全与公共安全、社会稳定与群体性事件、政治安全与意识形态、
重大舆情风险、公职人员违纪违法、特殊人群与弱势群体权益。
判定门槛从严：提及政府/部门等机构名称、投诉公职人员办事不力、
对处理结果不满要求督办等普通政务投诉一律不触发，
只有描述具体特殊事件（有事实、有危害、超出普通投诉范畴）才判敏感，
避免普通诉求被误剥离出正常办理流程。
"""
from app.core.ai.llm_client import chat_json

# 敏感事件六大类风险类型（白名单：LLM 输出不在清单内一律归为 none）
SENSITIVE_RISK_TYPES = (
    "人身安全与公共安全",
    "社会稳定与群体性事件",
    "政治安全与意识形态",
    "重大舆情风险",
    "公职人员违纪违法",
    "特殊人群与弱势群体权益",
)

SENSITIVE_SYSTEM_PROMPT = (
    "你是12345政务热线的敏感事件感知引擎。仅当诉求文本描述了明确的特殊事件、"
    "且命中以下六类情形之一时，才判定为敏感事件（risk_type 输出对应类别名），否则一律输出 none。\n"
    "【判定总原则——三条同时满足才可判敏感】\n"
    "a) 诉求描述了具体发生的特殊事件（有明确的人/事/行为/后果，而非猜测、计划或情绪）；\n"
    "b) 该事件已造成或即将造成现实危害（人身伤亡、财产重大损失、涉众风险、社会影响）；\n"
    "c) 该事件明显超出普通政务投诉范畴，需要专人专线紧急介入。\n"
    "把握不准时一律输出 none：敏感事件会被剥离出正常办理流程由专人受理，"
    "误判会导致市民的正常诉求无法走常规办理，宁可漏报不可误报。\n"
    "【六类情形——从严认定】\n"
    "1. 人身安全与公共安全：已发生或正在发生的群体性食物中毒（有人发病）、"
    "已造成人员伤亡或迫近的安全生产事故、危化品正在泄漏、"
    "未成年人正在遭受霸凌/侵害、人员有明确自杀自残行为或计划并求助；\n"
    "2. 社会稳定与群体性事件：已出现聚集、围堵、游行、拉横幅等现实集体行动，"
    "或10人以上有组织的讨薪/集体维权且情绪激烈有对抗升级迹象、"
    "非法集资/P2P爆雷已引发大批受害者集中讨要、民族宗教冲突事件；\n"
    "3. 政治安全与意识形态：对党和国家领导人的不当言论、涉外/涉港澳台/涉疆涉藏敏感话题、"
    "邪教组织或非法传教活动举报；\n"
    "4. 重大舆情风险：事件已在社交媒体/媒体形成实际传播（明确的热搜、大量转发、媒体已报道介入），"
    "或诉求中有组织性煽动（号召网友集体发帖、动员围观）；\n"
    "5. 公职人员违纪违法：有具体违纪违法事实的实名举报——贪污受贿（有金额/情节）、"
    "索要好处、暴力执法致人受伤、伪造篡改证据且有录音/视频等实证；"
    "必须是具体个人+具体违法行为+证据，缺一不可；\n"
    "6. 特殊人群与弱势群体权益：未成年人/残疾人/老年人/孕妇正在遭受虐待、家暴、"
    "拐卖等侵害，或基本生存（食宿/医疗）已陷入现实危机急需救助。\n"
    "【负面清单——以下情形一律输出 none（普通政务投诉，走正常办理流程）】\n"
    "- 仅提及政府、部门、机关、街道办、领导等机构名称或人名，本身不构成任何敏感要素；\n"
    "- 投诉政府部门/公职人员办事不力、推诿扯皮、效率低、态度差、不作为、慢作为；\n"
    "- 对处理结果不满，要求复核、重新处理、督办、向上级反映、找领导；\n"
    "- 质疑执法或处罚结果不公（无暴力执法致伤等具体违法事实）；\n"
    "- 表达“再不解决就投诉/曝光/发帖/找媒体/上访”的意愿或威胁（事件本身未形成实际传播）；\n"
    "- 多人/多户反映同一问题（无聚集、围堵等现实集体行动）；\n"
    "- 噪音扰民、物业纠纷、日常维修、市政设施损坏、占道经营、咨询求助、普通投诉建议等一般性诉求，"
    "即使措辞激动、多次投诉、表达强烈不满；\n"
    "- 居民小区及公共场所设施故障（电梯故障或困人后已解救且无人受伤、水电中断、管道渗漏、"
    "道路破损、消防通道堵塞但未起火等），无论故障多频繁、多次反映未解决，"
    "只要未造成人员伤亡且不构成现实紧迫的生命威胁（如燃气泄漏扩散、建筑物坍塌、火灾蔓延）；\n"
    "- 不得仅因诉求文本出现“安全隐患”“太危险了”“政府”“部门”等字眼而判定为敏感事件。\n"
    '只输出JSON：{"risk_type":"人身安全与公共安全|社会稳定与群体性事件|政治安全与意识形态|'
    '重大舆情风险|公职人员违纪违法|特殊人群与弱势群体权益|none",'
    '"risk_level":"GENERAL|SEVERE|URGENT","advice":"处置建议"}'
    "风险等级按危害程度判断：一般GENERAL、较重SEVERE、紧急URGENT；"
    "risk_type 为 none 时 risk_level 固定输出 GENERAL。"
)


def detect_sensitive(text: str) -> dict:
    """敏感事件语义感知：仅命中六大类情形且满足从严门槛才触发告警；
    输出做空值/类型防御，避免 LLM 偶发 null 或数值型字段导致响应校验 500
    """
    result = chat_json(SENSITIVE_SYSTEM_PROMPT, text)
    risk_type = str(result.get("risk_type") or "none").strip()
    risk_level = str(result.get("risk_level") or "GENERAL").strip()
    if risk_level not in ("GENERAL", "SEVERE", "URGENT"):
        risk_level = "GENERAL"
    # 白名单校验：不在六大类清单内的输出（含旧三类极端情绪/群体事件苗头/公共安全）一律归为 none
    if risk_type not in SENSITIVE_RISK_TYPES:
        risk_type = "none"
    if risk_type == "none":
        risk_level = "GENERAL"
    return {
        "risk_type": risk_type,
        "risk_level": risk_level,
        "advice": str(result.get("advice") or ""),
    }
